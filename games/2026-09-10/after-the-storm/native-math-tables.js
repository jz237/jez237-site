export function createNativeSineTableWords(){
 const view=new DataView(new ArrayBuffer(4)),words=[];
 for(let index=0;index<4096;index++){
  let value=index*6.283185307/4096;
  const negativeSquare=-value*value;
  let power=negativeSquare*value,denominator=6,k=2;
  for(;k!==10;k+=4){
   const term=power/denominator,p2=power*negativeSquare;
   const d2=denominator*(k*(k*4+2)),p3=p2*negativeSquare;
   const d3=d2*((k+1)*((k+1)*4+2)),p4=p3*negativeSquare;
   const d4=d3*((k+2)*((k+2)*4+2));
   power=p4*negativeSquare;denominator=d4*((k+3)*((k+3)*4+2));
   value=(((value+term)+p2/d2)+p3/d3)+p4/d4;
  }
  // The final four terms retain the source's distinct double products.
  const p23=(power*negativeSquare)*negativeSquare;
  const d23=(denominator*420)*((k+1)*((k+1)*4+2));
  const final=(((value+power/denominator)+(power*negativeSquare)/(denominator*420))+p23/d23)
   +(p23*negativeSquare)/(d23*((k+2)*((k+2)*4+2)));
  view.setFloat32(0,final);words.push(view.getUint32(0));
 }
 return Object.freeze(words);
}
