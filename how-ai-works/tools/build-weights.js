#!/usr/bin/env node
/* Trains the tiny transformer the page ships with and writes js/weights.js.
   Re-run after changing any text in js/data.js (token ids depend on it):

     node how-ai-works/tools/build-weights.js           # train + write
     node how-ai-works/tools/build-weights.js --check   # gradient check only
*/
'use strict';
const fs = require('fs'), path = require('path');
const D = require('../js/data.js'), TinyGPT = require('../js/tinygpt.js');
const V = D.vocab;

function gradCheck() {
  const cfg = Object.assign({}, D.config, { d: 8, F: 12, f64: true });
  const m = new TinyGPT(cfg, 7), sq = D.corpus[100];
  const inp = sq.slice(0, -1), tgt = sq.slice(1);
  m.g.fill(0);
  m.lossGrad(inp, tgt, 1);
  const g = Float64Array.from(m.g);
  let worst = 0;
  const r = TinyGPT.rng(3);
  for (let t = 0; t < 400; t++) {
    const i = Math.floor(r() * m.size), keep = m.w[i], e = 1e-5;
    m.w[i] = keep + e; m.g.fill(0); const a = m.lossGrad(inp, tgt, 1);
    m.w[i] = keep - e; m.g.fill(0); const b = m.lossGrad(inp, tgt, 1);
    m.w[i] = keep;
    const num = (a - b) / (2 * e), err = Math.abs(num - g[i]) / Math.max(1e-7, Math.abs(num) + Math.abs(g[i]));
    if (Math.abs(num) > 1e-7 && err > worst) worst = err;
  }
  console.log('gradient check, worst relative error over 400 weights:', worst.toExponential(2));
  if (worst > 1e-4) { console.error('GRADIENT CHECK FAILED'); process.exit(1); }
}

function show(m, text, k) {
  const toks = [V.BOS].concat(D.tokenize(text).map(t => t.m)), p = m.next(toks);
  const top = Array.from(p, (x, i) => [i, x]).sort((a, b) => b[1] - a[1]).slice(0, k || 4);
  return text.padEnd(34) + ' -> ' + top.map(t => V.word(t[0]) + ' ' + (t[1] * 100).toFixed(0) + '%').join(', ');
}

function train() {
  const m = new TinyGPT(D.config, 20261110), r = TinyGPT.rng(11), data = D.corpus.slice();
  const EPOCHS = 140, B = 8, noise = id => (r() < 0.03 ? V.UNK : id);
  const t0 = Date.now();
  let steps = 0;
  for (let ep = 0; ep < EPOCHS; ep++) {
    for (let i = data.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)), t = data[i]; data[i] = data[j]; data[j] = t; }
    const lr = 0.012 * (ep < 100 ? 1 : 0.35);
    let loss = 0, nb = 0;
    for (let i = 0; i < data.length; i += B) { loss += m.trainBatch(data.slice(i, i + B), lr, noise); nb++; steps++; }
    if (ep % 20 === 0 || ep === EPOCHS - 1) console.log('epoch', String(ep).padStart(3), 'train loss', (loss / nb).toFixed(3), 'eval', m.evalLoss(D.corpus).toFixed(3));
  }
  console.log('trained', steps, 'steps in', ((Date.now() - t0) / 1000).toFixed(1) + 's,', m.size, 'weights, vocab', V.size);
  return { m, steps };
}

gradCheck();
if (process.argv.includes('--check')) process.exit(0);

const longest = Math.max.apply(null, D.corpus.concat(D.finetune).map(s => s.length));
if (longest - 1 > D.config.T) { console.error('a sentence is longer than the context window:', longest); process.exit(1); }
const split = D.SENTENCES.concat(D.FINETUNE).filter(s => D.tokenize(s).length !== s.split(' ').length);
console.log('vocab', V.size, '| longest sequence', longest, '| sentences', D.corpus.length, '| words split by the tokenizer:', split.length ? split.slice(0, 3) : 'none');

const out = train(), m = out.m;
const pk = m.pack(), back = TinyGPT.unpack(pk);
const loss = back.evalLoss(D.corpus);
console.log('loss after 16-bit round trip:', loss.toFixed(4), '(before:', m.evalLoss(D.corpus).toFixed(4) + ')');
['the cat sat on the', 'the gardener was tired so', 'the farmer was tired so', 'the cat was tired so', 'the gardener was hungry so',
  'the farmer was curious so he', 'the dog ate the food because it was', 'the gardener sang because', 'the dragon sat on the', 'the', 'the robot']
  .forEach(t => console.log('  ' + show(back, t)));

const file = path.join(__dirname, '..', 'js', 'weights.js');
fs.writeFileSync(file,
  '/* Generated by tools/build-weights.js — the tiny transformer after ' + out.steps + ' training steps on the\n' +
  '   sentences in data.js. 16-bit weights, base64. Do not edit by hand. */\n' +
  'window.LAB_WEIGHTS = ' + JSON.stringify({ signature: D.signature, steps: out.steps, loss: +loss.toFixed(4), cfg: pk.cfg, scales: pk.scales, data: pk.data }) + ';\n');
console.log('wrote', path.relative(process.cwd(), file), (fs.statSync(file).size / 1024).toFixed(1) + ' KB');
