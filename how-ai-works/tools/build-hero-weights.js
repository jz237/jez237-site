/* Trains the hero's feed-forward network on the nine 6x6 shapes and writes js/hero-weights.js.
   Uses the same js/mlp.js the page runs, so a visitor pressing "Train" in the hero repeats this.

     node how-ai-works/tools/build-hero-weights.js            train and write the weights
     node how-ai-works/tools/build-hero-weights.js --check    only check the gradients by nudging weights
*/
const fs = require('fs'), path = require('path');
const M = require('../js/mlp.js');

function gradCheck() {
  const net = new M.MLP([36, 10, 8, 9], 3), r = M.rng(5), x = M.shapes.make(4, r), y = 4;
  net.forward(x); net.backward(y);
  let worst = 0;
  for (let g = 0; g < net.G; g++) for (let n = 0; n < 40; n++) {
    const i = Math.floor(r() * net.W[g].length), keep = net.W[g][i], eps = 1e-3;
    net.W[g][i] = keep + eps; const up = -Math.log(net.forward(x)[y]);
    net.W[g][i] = keep - eps; const dn = -Math.log(net.forward(x)[y]);
    net.W[g][i] = keep;
    const num = (up - dn) / (2 * eps), ana = net.gW[g][i];
    worst = Math.max(worst, Math.abs(num - ana) / Math.max(1e-4, Math.abs(num) + Math.abs(ana)));
  }
  console.log('gradient check, worst relative error over 120 weights: ' + worst.toExponential(2));
  if (worst > 2e-2) { console.error('gradient check FAILED'); process.exit(1); }
}

gradCheck();
if (process.argv.includes('--check')) process.exit(0);

const STEPS = 4000, net = new M.MLP(M.SIZES, 11), r = M.rng(2026);
let loss = 0;
for (let s = 1; s <= STEPS; s++) {
  const l = M.trainStep(net, r, M.BATCH, s > STEPS * 0.75 ? M.LR * 0.35 : M.LR);
  loss = loss ? loss * 0.98 + l * 0.02 : l;
  if (s % 500 === 0) console.log('step ' + s + '  loss ' + loss.toFixed(3) + '  accuracy on fresh shapes ' + (M.accuracy(net, M.rng(900 + s), 1500) * 100).toFixed(1) + '%');
}
const full = M.accuracy(net, M.rng(77), 5000);
const pk = net.pack(), back = new M.MLP(M.SIZES, 1);
if (!back.unpack(pk)) throw new Error('packed weights did not load back');
const packed = M.accuracy(back, M.rng(77), 5000);
console.log('accuracy at full precision ' + (full * 100).toFixed(2) + '%, after packing to 8 bits ' + (packed * 100).toFixed(2) + '%');
if (packed < 0.95) { console.error('packed accuracy too low to ship'); process.exit(1); }

const out = '/* Generated by tools/build-hero-weights.js. Do not edit by hand. */\nwindow.HERO_WEIGHTS = ' +
  JSON.stringify({ steps: STEPS, accuracy: +packed.toFixed(4), sizes: pk.sizes, scales: pk.scales, data: pk.data }) + ';\n';
fs.writeFileSync(path.join(__dirname, '../js/hero-weights.js'), out);
console.log('wrote js/hero-weights.js (' + out.length + ' bytes)');
