import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const root = process.env.FISH_LAB_URL || 'http://127.0.0.1:8768/experiments/fish-health-lab/';
const output = process.env.FISH_LAB_QA_DIR || '/home/jez237/.openclaw/workspace/tmp/fish-health-ich-qa';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: '/usr/bin/google-chrome', args: ['--disable-dev-shm-usage'] });
const context = await browser.newContext({ viewport: { width: 1365, height: 950 } });
const checks = [], errors = [], writes = [], outboundObservations = [], aiRequests = [];
const sentinel = 'PRIVATE-OBSERVATION-QA-1567945894068748309';
context.on('request', request => {
  const content = request.url() + (request.postData() || '');
  if (content.includes(sentinel)) outboundObservations.push(request.url());
  if (/chatgpt\.com|api\.openai\.com|api\.anthropic\.com/.test(request.url())) aiRequests.push(request.url());
  if (!['GET','HEAD','OPTIONS'].includes(request.method()) && !/google-analytics\.com|cloudflareinsights\.com/.test(request.url())) writes.push(request.url());
});
const page = await context.newPage();
const watch = target => target.on('pageerror', error => errors.push(error.message));
watch(page);
const record = label => checks.push(label);
const action = (target, name) => target.locator('[data-action="' + name + '"]:visible');
const noOverflow = async target => assert.equal(await target.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
const currentStep = (target, n) => target.locator('[data-ich-step="' + n + '"]');
const images = async (target, n) => {
  const pair = currentStep(target, n).locator('.walk-image img');
  assert.equal(await pair.count(), 2);
  for (const img of await pair.all()) {
    await img.scrollIntoViewIfNeeded();
    await img.evaluate(el => el.decode());
    assert.equal(await img.evaluate(el => el.naturalWidth), 1024);
  }
};
const choose = async (target, name, value) => target.locator('input[name="ich-' + name + '"][value="' + value + '"]').check();
const openFresh = async target => {
  if (target.url() === root + '#ich') await target.reload({ waitUntil: 'networkidle' });
  else await target.goto(root + '#ich', { waitUntil: 'networkidle' });
};
const enter = async (target, pattern = 'dots', extent = 'Few or subtle visible changes') => {
  await openFresh(target);
  await choose(target, 'water', 'fresh'); await action(target, 'ich-next').click();
  await choose(target, 'pattern', pattern); await action(target, 'ich-next').click();
  await choose(target, 'extent', extent); await action(target, 'ich-tank').click();
};

