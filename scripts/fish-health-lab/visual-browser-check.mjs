import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const root = process.env.FISH_LAB_URL || 'http://127.0.0.1:8768/experiments/fish-health-lab/';
const output = process.env.FISH_LAB_QA_DIR || '/home/jez237/.openclaw/workspace/tmp/fish-health-visual-qa';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: '/usr/bin/google-chrome', args: ['--disable-dev-shm-usage'] });
const context = await browser.newContext({viewport:{width:1365,height:950}});
const page = await context.newPage(), checks = [], problems = [], photoPosts = [];
const record = label => checks.push(label);
page.on('pageerror', error => problems.push(error.message));
const noOverflow = async target => assert.equal(await target.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
const imageReady = async locator => { await locator.waitFor(); await locator.evaluate(img => img.decode()); assert.ok(await locator.evaluate(img => img.naturalWidth > 0)); };
await page.goto(root,{waitUntil:'networkidle'});
assert.equal(await page.locator('#library-view').isVisible(),true);
assert.equal(await page.locator('#guide-view').isVisible(),false);
assert.equal(await page.locator('#library-grid .condition-card').count(),15);
assert.equal(await page.locator('.pattern-filter').count(),12);
await noOverflow(page); record('visual library is the default, with 15 entries and 12 appearance filters');
assert.match(await page.locator('#library-count').innerText(),/6 illustrations in place · 84 image spaces to fill/);
assert.equal(await page.locator('img[src=""]').count(),0);
await imageReady(page.locator('#guide-sheet')); await imageReady(page.locator('#variation-sheet'));
record('existing ich guides load; empty slots are labeled and never broken-image URLs');
await page.screenshot({path:`${output}/desktop-library.png`});
await page.locator('[data-library-pattern="dots"]').click();
assert.equal(await page.locator('#library-grid .card-image[data-condition="ich-fresh"]').count(),1);
assert.equal(await page.locator('#library-grid .card-image[data-condition="fin-damage"]').count(),0);
assert.equal(await page.locator('#library-grid .card-image[data-condition="velvet-fresh"]').count(),1);
await page.locator('#library-water').selectOption('marine');
assert.equal(await page.locator('#library-grid .card-image[data-condition="ich-fresh"]').count(),0);
assert.equal(await page.locator('#library-grid .card-image[data-condition="ich-marine"]').count(),1);
record('appearance and water-type filters work together');
await page.locator('[data-action="all-patterns"]').click();
await page.locator('#library-grid .card-image[data-condition="ich-fresh"]').click();
assert.equal(await page.locator('#detail-content [data-slot]').count(),6);
await imageReady(page.locator('#detail-content .gallery-image img'));
await page.locator('#detail-content [data-slot="closeup"]').click();
await imageReady(page.locator('#detail-content .gallery-image img'));
assert.equal(await page.locator('#detail-content .gallery-slots .filled').count(),6);
await page.locator('#detail-content [data-slot="variations"]').click();
await imageReady(page.locator('#detail-content .gallery-image img'));
record('all six ich gallery views are filled and switch correctly');
await page.screenshot({path:`${output}/desktop-gallery.png`});
await page.locator('#detail-content [data-enlarge-entry]').click();
await imageReady(page.locator('#atlas-full'));
assert.match(await page.locator('#atlas-title').innerText(),/Different fish/);
await page.keyboard.press('Escape');
assert.equal(await page.locator('#detail-dialog').isVisible(),true); record('image enlargement closes back to its gallery');
await page.locator('#detail-content [data-compare="ich-fresh"]').click();
await page.keyboard.press('Escape');
await page.locator('#library-grid [data-compare="velvet-fresh"]').click();
await page.locator('#library-grid [data-compare="fin-damage"]').click();
assert.equal(await page.locator('#comparison-picks button').count(),2);
assert.match(await page.locator('#comparison-status').innerText(),/Two entries are already selected/); record('comparison selection is capped at two without silently replacing a choice');
await page.locator('[data-action="compare"]').click();
assert.equal(await page.locator('#compare-dialog .visual-gallery').count(),2);
assert.equal(await page.locator('#compare-dialog [data-slot]').count(),12);
assert.match(await page.locator('#compare-content').innerText(),/What could fool you/);
record('two-entry comparison includes all image views, look-alikes and confirmation checks');
assert.equal(await page.locator('input[type="file"]').count(),0);
assert.equal(await page.locator('a[href*="chatgpt"]').count(),0); record('comparison has no photo submission or chatbot handoff');
await page.screenshot({path:`${output}/desktop-comparison.png`});
await page.locator('#compare-dialog [data-use-pattern="ich-fresh"]').click();
assert.equal(await page.locator('#compare-dialog').isVisible(),false);
assert.equal(await page.locator('input[name="water"]:checked').inputValue(),'fresh');
assert.equal(await page.locator('.symptom-card[aria-pressed="true"]').count(),1);
assert.equal(await page.locator('[data-symptom="dots"]').getAttribute('aria-pressed'),'true');
assert.match(await page.locator('#visual-start-note').innerText(),/not a diagnosis/);
record('library-to-check handoff selects only the visible sign, not a disease diagnosis');
await page.locator('[data-action="next"]').click(); await page.locator('button[type="submit"]').click();
await page.locator('[data-action="case"]').click();
const notes = await page.locator('#case-text').inputValue();
assert.match(notes,/Visual page used to start this check \(NOT evidence of a diagnosis\): Freshwater ich/);
assert.match(notes,/manually chosen for comparison \(user selections, not diagnoses\): Freshwater ich; Freshwater velvet/);
record('case handoff labels visual selections as user choices, not AI or diagnostic evidence');
await page.keyboard.press('Escape'); await page.locator('[data-action="reset"]').click();
assert.equal(await page.locator('#comparison-tray').isVisible(),false);
assert.equal(await page.locator('#visual-start-note').isVisible(),false);
record('new-check reset clears visual origin and comparison choices');
const mobile = await context.newPage(); await mobile.setViewportSize({width:390,height:844});
mobile.on('pageerror',error=>problems.push(error.message));
await mobile.goto(root,{waitUntil:'networkidle'}); await noOverflow(mobile);
await mobile.screenshot({path:`${output}/mobile-library.png`});
await mobile.locator('#library-grid [data-compare="ich-fresh"]').click();
await mobile.locator('#library-grid [data-compare="ich-marine"]').click();
await mobile.locator('[data-action="compare"]').click();
await noOverflow(mobile);
assert.equal(await mobile.locator('#compare-dialog .visual-gallery').count(),2);
assert.equal(await mobile.locator('#compare-dialog [data-slot]').count(),12);
await mobile.locator('#compare-dialog [data-gallery="ich-fresh"] [data-slot="closeup"]').click();
await imageReady(mobile.locator('#compare-dialog [data-gallery="ich-fresh"] .gallery-image img'));
assert.equal(await mobile.locator('#compare-dialog').evaluate(el=>el.scrollWidth>el.clientWidth),false);
await mobile.screenshot({path:`${output}/mobile-comparison.png`});
record('mobile library and two-column comparison fit without horizontal overflow');
await mobile.keyboard.press('Escape');
await mobile.locator('[data-action="clear-compare"]').click();
await mobile.locator('#library-grid .card-image[data-condition="ich-marine"]').click();
assert.equal(await mobile.locator('#detail-content [data-slot]').count(),6);
assert.equal(await mobile.locator('#detail-dialog').evaluate(el=>el.scrollWidth>el.clientWidth),false);
await mobile.screenshot({path:`${output}/mobile-empty-gallery.png`});
record('mobile empty galleries retain all six usable image slots and readable labels');
assert.deepEqual(problems,[]);
await browser.close();
const result = {url:root,checks:checks.length,passed:checks,problems,photoPosts,screenshots:output};
await writeFile(`${output}/visual-browser-results.json`,JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
