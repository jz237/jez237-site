import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const root = process.env.FISH_LAB_URL || 'http://127.0.0.1:8768/experiments/fish-health-lab/';
const output = process.env.FISH_LAB_QA_DIR || '/home/jez237/.openclaw/workspace/tmp/fish-health-lab-qa';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', args: ['--disable-dev-shm-usage'] });
const context = await browser.newContext({ viewport: { width: 1365, height: 950 }, permissions: ['clipboard-read','clipboard-write'] });
const page = await context.newPage();
const problems = [], posts = [], checks = [];
page.on('pageerror', error => problems.push(error.message));
page.on('request', request => { if (request.method() === 'POST' && !/google|cloudflareinsights/.test(request.url())) posts.push(request.url()); });
await page.goto(root, { waitUntil: 'networkidle' });
await page.locator('.nav-tab[data-view="guide"]').click();
await page.locator('[data-symptom="dots"]').waitFor();
const record = label => checks.push(label);
const overflow = () => page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
assert.equal(await overflow(), false); record('desktop layout has no horizontal overflow');
assert.equal(await page.locator('.symptom-card').count(),12); record('all visual symptom selectors render');
await page.screenshot({ path: `${output}/desktop-start.png`, fullPage: true });
await page.locator('[data-action="next"]').click();
assert.match(await page.locator('#step-one-error').innerText(),/Choose a water type/); record('water type and a sign are required');
await page.locator('input[name="water"][value="fresh"]').check();
await page.locator('[data-symptom="dots"]').click();
assert.equal(await page.locator('[data-symptom="dots"]').getAttribute('aria-pressed'),'true');
await page.locator('#species').fill('<img src=x onerror=alert(1)>');
const beforePhoto = posts.length;
await page.locator('#photo-input').setInputFiles({ name:'private-fish.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64') });
await page.locator('#photo-preview img').waitFor();
assert.equal(posts.length,beforePhoto); record('local photo preview creates no upload request');
await page.locator('[data-action="next"]').click();
assert.equal(await page.locator('[data-step="2"]').isVisible(),true);
await page.locator('#ammonia').fill('-1');
await page.locator('button[type="submit"]').click();
assert.equal(await page.locator('[data-step="2"]').isVisible(),true); record('invalid negative water readings do not advance');
await page.locator('#ammonia').fill('1');
await page.locator('#nitrite').fill('0.5');
await page.locator('#affected').selectOption('several');
await page.locator('#tankAge').selectOption('new');
await page.locator('input[value="gasping"]').check();
assert.equal(await page.locator('#inline-urgent').isVisible(),true);
await page.locator('#notes').fill('No medicines yet. Test case with <script>alert(1)</script>.');
await page.locator('button[type="submit"]').click();
assert.equal(await page.locator('[data-step="3"]').isVisible(),true);
assert.match(await page.locator('.results-grid .condition-card').first().innerText(),/Water-quality/);
assert.equal(await page.locator('#results-content .urgent').count(),1); record('environment and distress warnings take priority');
assert.doesNotMatch(await page.locator('#results-content').innerText(),/Marine ich/); record('freshwater result cards exclude marine diagnoses');
await page.screenshot({ path:`${output}/desktop-results.png`,fullPage:true });
await page.locator('#results-content button[data-condition="ich-fresh"]').first().click();
assert.equal(await page.locator('#detail-dialog').isVisible(),true);
assert.match(await page.locator('#detail-content').innerText(),/microscope/);
await page.keyboard.press('Escape'); record('condition detail and reference links work');
await page.locator('[data-action="case"]').click();
const notes = await page.locator('#case-text').inputValue();
assert.match(notes,/has NOT been analyzed or sent/);
assert.match(notes,/<img src=x onerror=alert\(1\)>/);
assert.match(notes,/Not measured \/ unknown/);
await page.locator('[data-action="copy-case"]').click();
assert.equal(await page.evaluate(() => navigator.clipboard.readText()), notes);
const downloadEvent = page.waitForEvent('download');
await page.locator('[data-action="download-case"]').click();
const download = await downloadEvent;
assert.equal(download.suggestedFilename(),'fish-health-case.txt');
const chatLink = page.locator('#case-dialog a[href="https://chatgpt.com/"]');
assert.equal(await chatLink.count(),1); record('case copying, plain-text export and explicit AI handoff work');
await page.keyboard.press('Escape');
await page.locator('[data-action="reset"]').click();
assert.equal(await page.locator('#photo-preview img').count(),0);
assert.equal(await page.locator('#species').inputValue(),'');
assert.equal(await page.locator('.symptom-card[aria-pressed="true"]').count(),0); record('reset clears photo and observations');
await page.locator('.nav-tab[data-view="library"]').click();
await page.locator('#library-water').selectOption('marine');
await page.locator('#library-search').fill('ich');
assert.match(await page.locator('#library-grid').innerText(),/Marine ich/);
assert.doesNotMatch(await page.locator('#library-grid').innerText(),/Freshwater ich/); record('library search and water-type filtering work');
await page.locator('.nav-tab[data-view="guide"]').click();
await page.locator('[data-action="atlas"]').first().click();
await page.locator('#atlas-full').waitFor();
const atlasLoaded = await page.locator('#atlas-full').evaluate(img => img.complete && img.naturalWidth > 0);
if (!atlasLoaded) problems.push('Atlas asset did not load');
await page.keyboard.press('Escape');
const mobile = await context.newPage();
await mobile.setViewportSize({width:390,height:844});
mobile.on('pageerror',error=>problems.push(`mobile: ${error.message}`));
await mobile.goto(root,{waitUntil:'networkidle'});
await mobile.locator('.nav-tab[data-view="guide"]').click();
assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await mobile.screenshot({path:`${output}/mobile-start.png`,fullPage:true});
await mobile.locator('input[name="water"][value="marine"]').check();
await mobile.locator('[data-symptom="dust"]').click();
await mobile.locator('[data-symptom="breathing"]').click();
await mobile.locator('[data-action="next"]').click();
await mobile.locator('button[type="submit"]').click();
assert.equal(await mobile.locator('[data-step="3"]').isVisible(),true);
assert.equal(await mobile.locator('#results-content .urgent').count(),1);
assert.match(await mobile.locator('.results-grid').innerText(),/Marine velvet/);
assert.doesNotMatch(await mobile.locator('.results-grid').innerText(),/Freshwater velvet/);
assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await mobile.screenshot({path:`${output}/mobile-results.png`,fullPage:true}); record('mobile workflow and marine respiratory triage work');
assert.deepEqual(problems,[]);
await browser.close();
console.log(JSON.stringify({url:root,checks:checks.length,passed:checks,posts,problems,screenshots:output},null,2));
