// Bundles runtime/main.js into demos/jurassic-terrarium/dinos.js.
//
// The page already carries Three.js r186 inside the Weatherglass bundle, and it hands the whole
// namespace to modules as ctx.THREE. Loading a second copy would double the download and split
// instanceof checks, so 'three' is aliased to a shim that re-exports that namespace. The addons
// (GLTFLoader, SkeletonUtils, meshopt decoder) import 'three' and get the same objects.
import { build } from 'esbuild';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const out = join(root, '../../demos/jurassic-terrarium/dinos.js');

const THREE = await import('three');
const names = Object.keys(THREE).filter((k) => k !== 'default');
mkdirSync(join(root, '.cache'), { recursive: true });
const shim = join(root, '.cache/three-shim.js');
writeFileSync(
  shim,
  '// generated by tools/build-runtime.mjs\n' +
    'const T = window.__wg?.ctx?.THREE ?? {};\n' +
    names.map((n) => `export const ${n} = T.${n};`).join('\n') +
    '\n',
);

const watch = process.argv.includes('--watch');
const opts = {
  entryPoints: [join(root, 'runtime/main.js')],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: !process.argv.includes('--dev'),
  legalComments: 'none',
  outfile: out,
  plugins: [
    {
      name: 'three-shim',
      setup(b) {
        b.onResolve({ filter: /^three$/ }, () => ({ path: shim }));
      },
    },
  ],
  logLevel: 'info',
};
await build(opts);
