test('Ironfield draws an open asphalt figure-eight at physical width without painting its infields',()=>{
 const r=canvasRecorder(400),extent=145,scale=180/extent;
 drawQuarryMap(r.canvas,[],{x:18,z:14,radius:64},'race',0,[],{point:IRONFIELD.point,extent,halfWidth:IRONFIELD.halfWidth});
 const route=r.paints.find(p=>p.path.filter(c=>c[0]==='lineTo').length>100)!;assert.ok(route,'course must have a visible route');assert.equal(route.operation,'stroke');assert.equal(route.style.lineWidth,17*scale);assert.equal(route.style.lineJoin,'round');
 assert.equal(r.paints.filter(p=>p.operation==='fill').length,0,'road lobes must never be filled');
 const points=route.path.map(p=>({x:((p[1] as number)-200)/scale,z:(200-(p[2]as number))/scale}));
 assert.ok(Math.min(...points.map(p=>p.x))< -109&&Math.max(...points.map(p=>p.x))>109,'both lobes visible');
 assert.ok(Math.min(...points.map(p=>p.z))< -63&&Math.max(...points.map(p=>p.z))>63,'north/south road extent visible');
 assert.deepEqual(points[0],points.at(-1),'course closes without a filled polygon');
 let crossings=0;for(let i=1;i<points.length;i++){const a=points[i-1],b=points[i],dx=b.x-a.x,dz=b.z-a.z,t=Math.max(0,Math.min(1,-(a.x*dx+a.z*dz)/(dx*dx+dz*dz)));if(Math.hypot(a.x+dx*t,a.z+dz*t)<.03)crossings++;}
 assert.ok(crossings>=2,'both at-grade branches pass through centre');
 for(const p of points){assert.ok(IRONFIELD.distance(p.x,p.z)<.02);assert.ok(Math.hypot(p.x,p.z)+IRONFIELD.halfWidth<extent,'full route width fits circular clipping');}
});

test('course extent scales road, waypoint and car positions together while derby ignores course',()=>{
 const arena={x:18,z:14,radius:64};
 for(const [size,extent]of [[240,145],[400,180]]){
  const r=canvasRecorder(size),scale=size*.45/extent,car=cars[2];drawQuarryMap(r.canvas,[car],arena,'race',car.id,[waypoints[0]],{point:IRONFIELD.point,extent});
  assert.deepEqual(r.calls.find(c=>c[0]==='translate'),['translate',size/2+car.current.x*scale,size/2-car.current.z*scale]);
  assert.ok(r.calls.some(c=>c[0]==='arc'&&c[1]===size/2+58*scale&&c[2]===size/2+22*scale&&c[3]===10));
  const route=r.paints.find(p=>p.path.filter(c=>c[0]==='lineTo').length>100)!;assert.equal(route.style.lineWidth,12*scale,'optional halfWidth defaults to 6m');
 }
 const stock=canvasRecorder(400),extra=canvasRecorder(400);drawQuarryMap(stock.canvas,cars,arena,'derby',0);drawQuarryMap(extra.canvas,cars,arena,'derby',0,[],{point(){throw Error('derby must not sample course');},extent:145});assert.deepEqual(extra.calls,stock.calls);
});


