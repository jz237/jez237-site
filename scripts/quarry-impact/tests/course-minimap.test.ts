type Command=unknown[];
type Paint={operation:string;path:Command[];style:Record<string,unknown>};
function canvasRecorder(size:number){
 const calls:Command[]=[],paints:Paint[]=[],stack:Record<string,unknown>[]=[],gradients=new WeakMap<object,string>();let style:Record<string,unknown>={},path:Command[]=[],gradientId=0;
 const context=new Proxy({}as Record<string,unknown>,{
  set(_target,key,value){style[String(key)]=value;calls.push(['set',String(key),typeof value==='object'&&value?gradients.get(value):value]);return true;},
  get(_target,key){if(Object.hasOwn(style,key))return style[String(key)];return(...args:unknown[])=>{
   const name=String(key);calls.push([name,...args]);
   if(name==='createRadialGradient'){const id='gradient'+gradientId++,gradient={addColorStop(...stops:unknown[]){calls.push(['addColorStop',id,...stops]);}};gradients.set(gradient,id);return gradient;}
   if(name==='save')stack.push({...style});else if(name==='restore')style=stack.pop()!;
   else if(name==='beginPath')path=[];else if(['moveTo','lineTo','arc','ellipse','closePath'].includes(name))path.push([name,...args]);
   else if(name==='fill'||name==='stroke')paints.push({operation:name,path:path.map(c=>c.slice()),style:{...style}});
  };},
 });
 const canvas={width:size,getContext(type:string){calls.push(['getContext',type]);return context;}}as unknown as HTMLCanvasElement;
 return{canvas,calls,paints};
}
